/* Run with PLAYWRIGHT_MODULE pointing at an existing Playwright installation. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const { pathToFileURL } = require("node:url");
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || "playwright");
const viewer = path.resolve(__dirname, "..");
const reports = path.resolve(viewer, "../exercises/budget-and-unknown");
const output = path.join(viewer, "verification-search");
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true, ...(process.env.PLAYWRIGHT_BROWSER_CHANNEL ? { channel: process.env.PLAYWRIGHT_BROWSER_CHANNEL } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
  const errors = [], network = [], checks = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("request", request => { if (/^https?:/.test(request.url())) network.push(request.url()); });
  const expectText = async (selector, value) => assert.equal(await page.locator(selector).textContent(), value);
  const choose = name => page.locator("#report-file").setInputFiles(path.join(reports, `${name}-result.json`));
  const reportResults = () => page.locator(".summary-grid, .selection-grid, .comparison-grid").evaluateAll(nodes => nodes.map(node => node.textContent));
  try {
    await page.goto(pathToFileURL(path.join(viewer, "index.html")).href);
    await expectText("#budget-value", "Not assessed");
    assert.equal(await page.locator("#molecule-search").isDisabled(), true);
    assert.equal(await page.locator("#label-filter").isDisabled(), true);
    checks.push("empty page has no fabricated metrics");
    await choose("budget-100");
    await page.waitForFunction(() => document.querySelector("#budget-value").textContent === "100");
    assert.equal(await page.locator("#heuristic-selection li").count(), 100);
    assert.equal(await page.locator("#qed-selection li").count(), 100);
    checks.push("budget-100 displays both exact-100 selections");
    await choose("budget-10");
    await page.waitForFunction(() => document.querySelector("#budget-value").textContent === "10");
    await expectText("#heuristic-count", "2 / 10");
    await expectText("#qed-count", "1 / 10");
    assert.equal(await page.locator("#heuristic-selection li").count(), 10);
    assert.equal(await page.locator("#qed-selection li").count(), 10);
    assert.equal(await page.locator("#molecule-rows tr").count(), 120);
    const knownCalculations = await page.locator("#molecule-rows tr").evaluateAll(rows => rows.map(row => Array.from(row.cells).slice(0, 6).map(cell => cell.textContent)));
    await page.screenshot({ path: path.join(output, "budget-10.png"), fullPage: true });
    checks.push("budget-10 displays exact selections, invented-positive counts and all 120 rows");
    const knownResults = await reportResults();
    await page.locator("#molecule-search").fill("ALKANE-028");
    await expectText("#molecule-caption", "Showing 1 of 120 molecules");
    assert.equal(await page.locator("#molecule-rows tr").count(), 1);
    await expectText("#molecule-rows td:first-child", "alkane-028");
    assert.deepEqual(await reportResults(), knownResults);
    checks.push("ID search is case-insensitive and leaves report-level results unchanged");
    await page.locator("#molecule-search").fill("CCCCCC");
    await expectText("#molecule-caption", "Showing 115 of 120 molecules");
    checks.push("SMILES substring search shows the correct table count");
    await page.locator("#molecule-search").fill("ALKANE-02");
    await page.locator("#label-filter").selectOption("positive");
    assert.deepEqual(await page.locator("#molecule-rows td:first-child").allTextContents(), ["alkane-021", "alkane-028"]);
    await expectText("#molecule-caption", "Showing 2 of 120 molecules");
    assert.deepEqual(await reportResults(), knownResults);
    checks.push("search and invented-label filtering combine without changing selections or metrics");
    await page.locator("#clear-filters").click();
    await page.locator("#label-filter").selectOption("positive");
    await expectText("#molecule-caption", "Showing 17 of 120 molecules");
    await page.locator("#label-filter").selectOption("negative");
    await expectText("#molecule-caption", "Showing 103 of 120 molecules");
    await page.locator("#label-filter").selectOption("unknown");
    await expectText("#molecule-caption", "Showing 0 of 120 molecules");
    assert.equal(await page.locator("#molecule-empty").isVisible(), true);
    assert.deepEqual(await reportResults(), knownResults);
    checks.push("positive, negative and empty unknown filters preserve complete-report comparisons");
    await page.locator("#molecule-search").fill("alkane-028");

    await page.evaluate(() => {
      const original = File.prototype.text;
      File.prototype.text = async function () {
        await new Promise(resolve => { window.releaseRead = resolve; });
        return original.call(this);
      };
      window.restoreFileRead = () => { File.prototype.text = original; };
    });
    await choose("budget-10-unknown");
    await expectText("#heuristic-count", "Not assessed");
    await expectText("#qed-count", "Not assessed");
    await expectText("#difference-value", "Not assessed");
    assert.equal(await page.locator("#heuristic-selection li, #qed-selection li").count(), 0);
    checks.push("previous selections and metrics disappear before the next file finishes reading");
    assert.equal(await page.locator("#molecule-search").inputValue(), "");
    assert.equal(await page.locator("#label-filter").inputValue(), "all");
    assert.equal(await page.locator("#molecule-search").isDisabled(), true);
    await page.evaluate(() => { window.releaseRead(); window.restoreFileRead(); });
    await page.waitForFunction(() => document.querySelector("#status-value").textContent === "Insufficient evidence");
    await expectText("#scored-value", "120");
    for (const id of ["heuristic-count", "qed-count", "difference-value", "random-value", "enrichment-value"]) await expectText(`#${id}`, "Not assessed");
    assert.equal(await page.locator("#heuristic-selection li, #qed-selection li").count(), 0);
    assert.equal(await page.locator("#molecule-rows tr").count(), 120);
    assert.deepEqual(await page.locator("#molecule-rows tr").evaluateAll(rows => rows.map(row => Array.from(row.cells).slice(0, 6).map(cell => cell.textContent))), knownCalculations);
    assert.equal(await page.locator("#molecule-rows tr", { hasText: "alkane-028" }).locator(".label-unknown").textContent(), "Unknown");
    await page.locator("#molecule-rows tr").last().scrollIntoViewIfNeeded();
    assert.equal(await page.locator("#molecule-rows tr").last().locator("td").first().textContent(), "alkane-120");
    await page.locator(".table-scroll").evaluate(table => { table.scrollTop = 0; });
    await page.screenshot({ path: path.join(output, "unknown-label.png"), fullPage: true });
    checks.push("unknown report retains all 120 molecular calculations and clears every outcome comparison");
    const unknownResults = await reportResults();
    await page.locator("#label-filter").selectOption("unknown");
    await expectText("#molecule-caption", "Showing 1 of 120 molecules");
    assert.deepEqual(await page.locator("#molecule-rows td:first-child").allTextContents(), ["alkane-028"]);
    assert.deepEqual(await reportResults(), unknownResults);
    await page.screenshot({ path: path.join(output, "unknown-filter.png"), fullPage: true });
    checks.push("Unknown shows only alkane-028 while every comparison remains Not assessed");
    await page.locator("#label-filter").selectOption("all");
    await expectText("#molecule-caption", "Showing 120 of 120 molecules");
    assert.equal(await page.locator("#molecule-rows tr").count(), 120);
    assert.deepEqual(await reportResults(), unknownResults);
    checks.push("clearing Unknown restores all 120 rows without changing report-level results");
    await page.locator("#molecule-search").fill("no-such-molecule");
    await expectText("#molecule-caption", "Showing 0 of 120 molecules");
    assert.equal(await page.locator("#molecule-rows tr").count(), 0);
    assert.deepEqual(await reportResults(), unknownResults);
    await page.locator("#clear-filters").click();
    await expectText("#molecule-caption", "Showing 120 of 120 molecules");
    checks.push("no-match search has an empty state; Clear filters restores the full table");
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.equal(await page.locator(".synthetic-banner strong").textContent(), "Synthetic learning data");
    await page.screenshot({ path: path.join(output, "mobile.png"), fullPage: true });
    checks.push("mobile view fits the viewport with the synthetic label intact");

    await choose("budget-10");
    await page.waitForFunction(() => document.querySelector("#status-value").textContent === "Complete");
    await page.locator("#report-file").setInputFiles({ name: "broken.json", mimeType: "application/json", buffer: Buffer.from("{") });
    await page.waitForFunction(() => !document.querySelector("#load-error").hidden);
    assert.equal(await page.locator("#label-filter").isDisabled(), true);
    await expectText("#difference-value", "Not assessed");
    assert.equal(await page.locator("#heuristic-selection li, #molecule-rows tr").count(), 0);
    checks.push("invalid files clear the old report and show an error");

    const hostile = JSON.parse(fs.readFileSync(path.join(reports, "budget-10-result.json"), "utf8"));
    hostile.rows[0].chemistry.canonical_isomeric_smiles = '<img src=x onerror="window.injected=true">';
    await page.locator("#report-file").setInputFiles({ name: "text-only.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(hostile)) });
    await page.waitForFunction(() => document.querySelector("#status-value").textContent === "Complete");
    assert.equal(await page.locator("#molecule-rows img").count(), 0);
    assert.equal(await page.evaluate(() => window.injected === true), false);
    checks.push("file content is rendered as text, never HTML");
    await page.locator("#clear-report").click();
    await expectText("#status-value", "Not assessed");
    assert.equal(await page.locator("#molecule-rows tr").count(), 0);
    checks.push("clear removes the current report");
    assert.deepEqual(errors, []);
    assert.deepEqual(network, []);
    checks.push("no browser errors or HTTP requests");
    fs.writeFileSync(path.join(output, "browser-checks.json"), JSON.stringify({ passed: checks.length, checks, browserErrors: errors, httpRequests: network }, null, 2) + "\n");
    console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
