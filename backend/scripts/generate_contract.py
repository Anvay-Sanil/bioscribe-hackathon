"""Generate reviewable JSON Schema/OpenAPI and TypeScript from the Pydantic authority."""
import json
from pathlib import Path
import sys
sys.path.insert(0,str(Path(__file__).resolve().parents[1]))
from bioscribe.api import create_app
from bioscribe.schemas import RunRequest, RunView
from bioscribe.registry import METHODS

ROOT=Path(__file__).resolve().parents[2]


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "oneOf" in schema:
        return "("+" | ".join(ts(value) for value in schema["oneOf"])+")"
    if "anyOf" in schema:
        return "("+" | ".join(ts(value) for value in schema["anyOf"])+")"
    kind=schema.get("type")
    if kind=="object":
        if "properties" in schema:
            required=schema.get("required",[])
            return "{\n"+"\n".join(f'  {json.dumps(name)}{"" if name in required else "?"}: {ts(value)};' for name,value in schema["properties"].items())+"\n}"
        return "{[key: string]: "+ts(schema.get("additionalProperties",{}))+"}"
    if kind=="array":
        return "Array<"+ts(schema["items"])+">"
    return {"string":"string","number":"number","integer":"number","boolean":"boolean","null":"null"}.get(kind,"unknown")


def main():
    target=ROOT/"bioscribe-ai/src/lib/phase3"
    target.mkdir(parents=True,exist_ok=True)
    definitions={}
    lines=["// Generated by backend/scripts/generate_contract.py. Do not edit."]
    for model in (RunRequest,RunView):
        schema=model.model_json_schema(mode="serialization")
        definitions.update(schema.get("$defs",{}))
        (target/(model.__name__+".schema.json")).write_text(json.dumps(schema,indent=2)+"\n",encoding="utf-8")
        definitions[model.__name__]=schema
    for name,schema in definitions.items():
        lines.append(f"export type {name} = {ts(schema)};")
    lines.append("export type Artifact = CurrentArtifact | HistoricalArtifact;")
    (target/"contract.ts").write_text("\n\n".join(lines)+"\n",encoding="utf-8")
    (target/"methods.json").write_text(json.dumps(METHODS,indent=2)+"\n",encoding="utf-8")
    (ROOT/"docs/PHASE_3_OPENAPI.json").write_text(json.dumps(create_app().openapi(),indent=2)+"\n",encoding="utf-8")


if __name__=="__main__":
    main()
